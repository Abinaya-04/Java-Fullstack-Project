public class Food {
    private int id;
    private String dish;
    private double price;

    public int getId() {
        return id;
    }

    public String getDish() {
        return dish;
    }

    public double getPrice() {
        return price;
    }

    public void setId(int id) { this.id = id; }

    public void setDish(String dish) { this.dish = dish; }

    public void setPrice(double price) { this.price = price; }
}
